package DataBeans;

/**
 *
 * @author dell
 */
public class D3DataBean {
    
    private int cdfId;
    private String billingDay;
    private String billingDate;
    private String meterSerialNo;
    private String d3TimeStamp;
    private String logTimeStamp;

    public int getCdfId() {
        return cdfId;
    }

    public void setCdfId(int cdfId) {
        this.cdfId = cdfId;
    }

    public String getBillingDay() {
        return billingDay;
    }

    public void setBillingDay(String billingDay) {
        this.billingDay = billingDay;
    }

    public String getBillingDate() {
        return billingDate;
    }

    public void setBillingDate(String billingDate) {
        this.billingDate = billingDate;
    }

    public String getMeterSerialNo() {
        return meterSerialNo;
    }

    public void setMeterSerialNo(String meterSerialNo) {
        this.meterSerialNo = meterSerialNo;
    }

    public String getD3TimeStamp() {
        return d3TimeStamp;
    }

    public void setD3TimeStamp(String d3TimeStamp) {
        this.d3TimeStamp = d3TimeStamp;
    }

    public String getLogTimeStamp() {
        return logTimeStamp;
    }

    public void setLogTimeStamp(String logTimeStamp) {
        this.logTimeStamp = logTimeStamp;
    }
    
    
}

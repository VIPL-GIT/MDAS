public class MeterMakeBean {
 
    private int meterMakeId;
    private String meterMakeName;
    private String meterSeries;
    private String meterVersion;

    public int getMeterMakeId() {
        return meterMakeId;
    }

    public void setMeterMakeId(int meterMakeId) {
        this.meterMakeId = meterMakeId;
    }

    public String getMeterMakeName() {
        return meterMakeName;
    }

    public void setMeterMakeName(String meterMakeName) {
        this.meterMakeName = meterMakeName;
    }

    public String getMeterSeries() {
        return meterSeries;
    }

    public void setMeterSeries(String meterSeries) {
        this.meterSeries = meterSeries;
    }

    public String getMeterVersion() {
        return meterVersion;
    }

    public void setMeterVersion(String meterVersion) {
        this.meterVersion = meterVersion;
    }
    
    
}

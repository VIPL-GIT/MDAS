package com.rtdas.feeder_reports.beans;

public class PowerFailuresBean {

	private String meter_serial_no;
	private String trans_pf;
	private String sust_pf;
	
	
	public String getMeter_serial_no() {
		return meter_serial_no;
	}
	public void setMeter_serial_no(String meter_serial_no) {
		this.meter_serial_no = meter_serial_no;
	}
	public String getTrans_pf() {
		return trans_pf;
	}
	public void setTrans_pf(String trans_pf) {
		this.trans_pf = trans_pf;
	}
	public String getSust_pf() {
		return sust_pf;
	}
	public void setSust_pf(String sust_pf) {
		this.sust_pf = sust_pf;
	}
	
	
}

package DataBeans;

/**
 *
 * @author dell
 */
public class D6DataBean {
 
    private int cdfid;
    private String snapShotDate;
    private String dataString;
    private String meterSerialNo;
    private String d6TimeStamp;
    private String logTimeStamp;

    public int getCdfid() {
        return cdfid;
    }

    public void setCdfid(int cdfid) {
        this.cdfid = cdfid;
    }

    public String getSnapShotDate() {
        return snapShotDate;
    }

    public void setSnapShotDate(String snapShotDate) {
        this.snapShotDate = snapShotDate;
    }

    public String getDataString() {
        return dataString;
    }

    public void setDataString(String dataString) {
        this.dataString = dataString;
    }

    public String getMeterSerialNo() {
        return meterSerialNo;
    }

    public void setMeterSerialNo(String meterSerialNo) {
        this.meterSerialNo = meterSerialNo;
    }

    public String getD6TimeStamp() {
        return d6TimeStamp;
    }

    public void setD6TimeStamp(String d6TimeStamp) {
        this.d6TimeStamp = d6TimeStamp;
    }

    public String getLogTimeStamp() {
        return logTimeStamp;
    }

    public void setLogTimeStamp(String logTimeStamp) {
        this.logTimeStamp = logTimeStamp;
    }
    
    
}
